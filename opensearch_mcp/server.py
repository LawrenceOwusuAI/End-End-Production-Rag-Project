from __future__ import annotations
import os
from datetime import datetime,timedelta,timezone
from mcp.server import MCPServer
from opensearch_mcp.opensearch_client import search_opensearch

# MCP SERVER
mcp = MCPServer("rag-opensearch-observability")

# INDEX PATTERNS
LOG_INDEX = os.getenv("OPENSEARCH_LOG_INDEX","logs-otel-v1-*")
TRACE_INDEX = os.getenv("OPENSEARCH_TRACE_INDEX","otel-v1-apm-span-*")

# SAFE TIME WINDOW
def get_start_time(minutes: int):
    minutes = max(1,min(minutes,1440))
    start = (datetime.now(timezone.utc)-timedelta(minutes=minutes))
    return start.isoformat()

# TOOL 1: RECENT USER QUERIES
@mcp.tool()
async def get_recent_user_queries(minutes: int = 30, limit: int = 20) -> dict:

    """
    Return recent user questions sent to the RAG application.
    """

    limit = min(
        max(
            limit,
            1,
        ),
        100,
    )


    query = {

        "size":
            limit,

        "sort": [
            {
                "@timestamp":
                    "desc"
            }
        ],

        "query": {

            "bool": {

                "filter": [

                    {
                        "range": {

                            "@timestamp": {

                                "gte":
                                    get_start_time(
                                        minutes
                                    )
                            }
                        }
                    }

                ],

                "should": [

                    {
                        "term": {

                            "attributes.rag_event.keyword":
                                "rag.query"
                        }
                    },

                    {
                        "match_phrase": {

                            "body":
                                "RAG user query received"
                        }
                    },

                ],

                "minimum_should_match":
                    1,
            }
        }
    }


    result = search_opensearch(
        LOG_INDEX,
        query,
    )


    return {
        "minutes":
            minutes,

        "queries":
            result[
                "hits"
            ][
                "hits"
            ],
    }

