# TOOL 14 FAILURE INVESTIGATION
@mcp.tool()
async def investigate_rag_failure(minutes: int = 15) -> dict:

    """
    Gather diagnostic evidence useful for investigating
    recent RAG failures.
    """
    errors = await get_recent_errors(minutes=minutes,limit=20)
    retrieval_errors = await get_retrieval_errors( minutes=minutes,limit=20)
    llm_errors = await get_llm_errors(minutes=minutes,limit=20)
    vector_database_errors = await get_vector_database_errors(minutes=minutes,limit=20)
    return {
        "recent_errors":errors,
        "retrieval_errors":retrieval_errors,
        "llm_errors":llm_errors,
        "vector_database_errors":vector_database_errors,
    }

# TOOL 15 COMPLETE RECENT RAG ACTIVITY
@mcp.tool()
async def get_recent_rag_activity(minutes: int = 15) -> dict:

    """
    Retrieve recent:
    - user queries
    - retrieved document chunks
    - generated answers
    - errors
    """
    queries = await get_recent_user_queries(minutes=minutes,limit=20)
    documents = await get_recent_retrieved_documents(minutes=minutes,limit=40)
    answers = await get_recent_generated_answers(minutes=minutes,limit=20)
    errors = await get_recent_errors(minutes=minutes,limit=20)
    return {
        "queries":queries,
        "retrieved_documents":documents,
        "generated_answers":answers,
        "errors":errors,
    }

